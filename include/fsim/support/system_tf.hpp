// The system task or function a system_tf_identifier (with its `$`) names;
// none for a name IEEE 1800-2023 does not define.
[[nodiscard]] constexpr SystemTf system_tf_named(
    const std::string_view name) noexcept
{
    const auto& table = detail::kSystemTfNames;
    const auto found = std::ranges::lower_bound(
        table, name, { }, &std::pair<std::string_view, SystemTf>::first);
    return found != table.end() && found->first == name ? found->second
                                                         : SystemTf::none;
}

// The system_tf_identifier of a system task or function, with its `$`
// (empty for none).
[[nodiscard]] constexpr std::string_view system_tf_name(
    const SystemTf routine) noexcept
{
    for (const auto& [name, value] : detail::kSystemTfNames) {
        if (value == routine && routine != SystemTf::none) {
            return name;
        }
    }
    return { };
}

